#!/usr/bin/env python3
"""Generate the Monte Carlo pilot decks and `klt sim` requests (issue #174).

    python3 -I sim/mc-pilot/gen_mc_pilot.py            # (re)write the committed files
    python3 -I sim/mc-pilot/gen_mc_pilot.py --check    # fail if a committed file is stale

Any other argument is a usage error (exit 2) and writes nothing; the shared
driver in ``sim/lib/bench_gen.py`` says why.

The item-9 pilot measures what variation the pinned HBT sections and batch
runner produce. Its feasibility evidence feeds the PROPOSED decision record
``spec/decision-records/0005-statistical-rows.md``.

Writes, for the DUT ``design/netlist/sg13g2-pa.spice`` (inlined verbatim, the
same way every DUT bench does):

* ``sim/mc-pilot/mc_op.spice``                      DC operating point, per-device Ic
* ``sim/mc-pilot/mc_ac_gain.spice``                 byte-identical to the attested
  ``sim/ac-gain/ac_gain.spice`` (generated by the same ``ac_gain_deck()`` call,
  never hand-copied), so the pilot's S21/S11 come from the committed bench deck
* ``sim/mc-pilot/mc_op_{stat,mismatch}.request.json``    MC over ``hbt_typ_stat`` /
  ``hbt_typ_mismatch``; the two sections are run separately so the process-only
  and per-instance-mismatch mechanisms are measured apart
* ``sim/mc-pilot/mc_ac_{stat,mismatch}.request.json``    the same two sections on the
  AC bench
* ``sim/mc-pilot/probe_{scale,instances}.request.json``  the negative-control probes
  (``monte_carlo.mismatch_scale`` / ``monte_carlo.instances``); at the pinned
  client these are refused before any draw, and the refusal is the evidence

The bench facts a record must restate -- the sample count, the seed, the
nominal cell and the per-device vector names -- are declared here once;
``mc_pilot_record.py`` imports them rather than keeping its own copies. The DUT
facts (nominal cell, port impedances) come from ``sim/lib/gen_dut_benches.py``,
the single source every DUT bench shares.

Nothing here is a result; the decks and requests are simulated benches. The
DUT's output network is ideal passives (see ``design/README.md``), and every
request says so through the deck headers.
"""
import json
import os
import pathlib
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "lib"))
import bench_gen  # noqa: E402
import gen_dut_benches as gdb  # noqa: E402

REPO = pathlib.Path(__file__).resolve().parents[2]

# --- The pilot's own facts ------------------------------------------------
#
# Sample count and seed: the pilot's job is to show the two mechanisms work and
# to bound the spread, not to make a yield claim; n=100 puts roughly +/-10 % on
# a sigma estimate (sigma of the sigma estimate ~ sigma/sqrt(2n)), which is
# enough to size the eventual campaign. The seed is arbitrary and recorded: the
# same request reproduces the same draws (klt's seed contract).
N_SAMPLES = 100
SEED = 174

# Per-unit timeout: a cold local op/AC unit solves in ~1-2 s (probe runs for
# issue #174, 2026-11-20); 120 s is ~60x that, and keeps every shard of the
# 100-unit request inside the fleet's whole-job ceiling (``remote.hosts`` below
# is derived from it the way gen_dut_benches.batch_hosts derives the psat's).
UNIT_TIMEOUT_S = 120

# The two statistical sections of cornerHBT.lib, run separately (issue #174):
# hbt_typ_stat includes sg13g2_hbt_stat.lib (global gauss() on the vbic_*
# multipliers -- one draw per deck evaluation, common to every instance) plus
# the standard sg13g2_hbt_mod.lib (no per-instance terms); hbt_typ_mismatch
# includes sg13g2_hbt_mod_mismatch.lib, whose npn13G2 declares mm_ok=1 and
# qarea='agauss(1, 0.1, ...)' -- per-instance. The `vary` axis names the
# mechanism each section actually exercises; for these decks it is a label,
# not a control (klt feeds ngspice one combined rndseed either way -- see the
# request comment in mc_pilot_record.py's "Tool check" section).
SECTIONS = {
    "stat": ("hbt_typ_stat", "process"),
    "mismatch": ("hbt_typ_mismatch", "mismatch"),
}

# The collector-current vectors of X1's 15 HBTs: the 14 output array devices
# (XQ1..XQ14, identically biased) and the diode-connected mirror reference
# (XQref, a different operating point). ngspice needs the device-type prefix
# (`q.`) on a hierarchical device vector; without it the vector does not
# resolve (probed for this issue, ngspice-47).
OUTPUT_DEVICES = [f"xq{i}" for i in range(1, 15)]
REFERENCE_DEVICE = "xqref"


def device_ic(dev):
    return f"@q.x1.{dev}.qnpn13g2[ic]"


def dc_measurements():
    """The op request's measurements, in declared order.

    Per-device currents first (the thing being measured: one draw's 14 output
    currents stay separate, and nothing divides the array current by 14 -- that
    would erase the per-instance mismatch). `ic_total` and `ic_diff_12` then
    read earlier measurements' names, so klt's own Monte Carlo rollup reports
    their mean/stddev/quantiles tool-computed. `ic_diff_12` is the same-draw
    difference between two identically biased output devices: it carries
    mismatch but no common movement, which is what separates the two sections'
    effects. `icc_vcc` cross-checks the sum against the supply branch.
    """
    meas = [{"name": f"ic{i}", "expr": device_ic(dev), "unit": "A"}
            for i, dev in enumerate(OUTPUT_DEVICES, start=1)]
    total = " + ".join(device_ic(dev) for dev in OUTPUT_DEVICES)
    meas.append({"name": "ic_total", "expr": total, "unit": "A"})
    meas.append({"name": "ic_diff_12", "expr": "ic1 - ic2", "unit": "A"})
    meas.append({"name": "ic_ref", "expr": device_ic(REFERENCE_DEVICE), "unit": "A"})
    meas.append({"name": "icc_vcc", "expr": "i(vcc)", "unit": "A"})
    return meas


def dc_deck():
    """The DC operating-point deck: the DUT verbatim, at Vcc, RF-terminated."""
    h = gdb._header(
        "Monte Carlo pilot: quiescent operating point, per-device collector current "
        "(simulated bench, not a result; a PILOT on a design that does not meet its rows)",
        [
            f"Vcc = {gdb.VCC_NOM_V:g} V; the bias is the DUT's own mirror (Iref/XQref/Rb).",
            "RFOUT is DC-blocked (Cblock) and RFIN likewise (Cin), so Rl/Rin set no DC path;",
            f"both are {gdb.RL_OHM:g} ohm, the RF terminations of the other benches.",
            "Per-device quiescent Ic is read from the model's own device vectors by the",
            "request's expr measurements (@q.x1.<dev>.qnpn13g2[ic]; ngspice-47 needs the",
            "type prefix on a hierarchical device vector). One draw's 14 output currents",
            "stay separate; the array current is never divided by 14, which would erase",
            "the per-instance mismatch being measured.",
            "Output network: IDEAL passives (Lchoke, Cblock, Cin in the DUT); Iref, Rb and",
            "the terminations are ideal and contribute no variation.",
        ],
    )
    body = f"""Vcc vcc 0 dc {gdb.VCC_NOM_V}
X1 rfin rfout vcc 0 sg13g2-pa
Rl rfout 0 {gdb.RL_OHM:g}
Rin rfin 0 {gdb.RS_OHM:g}
"""
    # gdb._header stamps its own generator name on line 2; this deck is written
    # by gen_mc_pilot.py, and a header naming the wrong regenerator would send
    # whoever edits the DUT to a file that does not write this deck.
    lines = h.split("\n")
    lines[1] = "* GENERATED by sim/mc-pilot/gen_mc_pilot.py -- do not edit; rerun it."
    return "\n".join(lines) + gdb._dut_block() + body


def _mc(section_key, extra=None):
    section, vary = SECTIONS[section_key]
    mc = {"n": N_SAMPLES, "seed": SEED, "vary": vary}
    if extra:
        mc.update(extra)
    return mc, section


def _process(section):
    return [{"name": section, "sections": [{"lib": bench_gen.CORNER_LIB, "section": section}]}]


def dc_request(section_key):
    mc, section = _mc(section_key)
    return {
        "netlist": "mc_op.spice",
        "models": {"pdk": bench_gen.PDK_NAME},
        "corners": {"process": _process(section), "temperature_c": [gdb.TEMP_NOM_C]},
        "analysis": {"kind": "op", "args": ""},
        "monte_carlo": mc,
        "measurements": dc_measurements(),
        "options": {"timeout_s": UNIT_TIMEOUT_S, "keep_artifacts": True,
                    "ngspice_init": ["set numdgt=8"]},
        "batch": {"capacity_wait_s": bench_gen.CAPACITY_WAIT_S},
        "remote": {"hosts": gdb.batch_hosts(N_SAMPLES, UNIT_TIMEOUT_S)},
    }


def ac_request(section_key):
    mc, section = _mc(section_key)
    return {
        "netlist": "mc_ac_gain.spice",
        "models": {"pdk": bench_gen.PDK_NAME},
        "corners": {"process": _process(section), "temperature_c": [gdb.TEMP_NOM_C]},
        "analysis": {"kind": "ac", "args": f"lin 11 {gdb.BAND_LO_HZ:g} {gdb.BAND_HI_HZ:g}"},
        "monte_carlo": mc,
        "options": gdb._ac_options() | {"timeout_s": UNIT_TIMEOUT_S},
        "batch": {"capacity_wait_s": bench_gen.CAPACITY_WAIT_S},
        "remote": {"hosts": gdb.batch_hosts(N_SAMPLES, UNIT_TIMEOUT_S)},
    }


def probe_scale_request():
    """`mismatch_scale: 0` on the mismatch section: the requested perturbation is
    'switch the family's multiplicative mismatch off so every draw is identical'
    (sigma = 0); the expected effect at the pinned 0.9.0 client is a refusal
    naming the two-family curation (2AMLogic/klayout-tools#5486)."""
    mc, section = _mc("mismatch", extra={"mismatch_scale": 0})
    req = dc_request("mismatch")
    req["monte_carlo"] = mc
    req.pop("batch")
    req.pop("remote")
    req["backend"] = "local"
    req["options"] = dict(req["options"])
    req["options"]["timeout_s"] = 60
    return req


def probe_instances_request():
    """`instances: {include: [x1.xq1]}`: the requested perturbation is 'gate
    per-instance mismatch to X1's first output device only' (its agauss stays,
    every other instance's is shadowed off); expected effect at the pinned
    0.9.0 client is the same two-family refusal (the sg13g2 `mm_ok` gate is
    2AMLogic/klayout-tools#5487, completed upstream after the 0.9.0 pin)."""
    mc, section = _mc("mismatch", extra={"instances": {"include": ["x1.xq1"]}})
    req = dc_request("mismatch")
    req["monte_carlo"] = mc
    req.pop("batch")
    req.pop("remote")
    req["backend"] = "local"
    req["options"] = dict(req["options"])
    req["options"]["timeout_s"] = 60
    return req


def outputs():
    """{repo-relative path: text}"""
    def j(obj):
        return json.dumps(obj, indent=2) + "\n"

    out = {
        "sim/mc-pilot/mc_op.spice": dc_deck(),
        # Byte-identical to the attested sim/ac-gain/ac_gain.spice: generated by
        # the same gen_dut_benches.ac_gain_deck() the committed deck is gated by
        # (its --check recomputes it from the DUT netlist), never hand-copied.
        "sim/mc-pilot/mc_ac_gain.spice": gdb.ac_gain_deck(),
        "sim/mc-pilot/probe_scale.request.json": j(probe_scale_request()),
        "sim/mc-pilot/probe_instances.request.json": j(probe_instances_request()),
    }
    for key in ("stat", "mismatch"):
        out[f"sim/mc-pilot/mc_op_{key}.request.json"] = j(dc_request(key))
        out[f"sim/mc-pilot/mc_ac_{key}.request.json"] = j(ac_request(key))
    return out


def main(args):
    return bench_gen.write_or_check(
        outputs(), args, "gen_mc_pilot.py", REPO,
        "python3 -I sim/mc-pilot/gen_mc_pilot.py",
        ok_message="committed pilot decks match design/netlist/sg13g2-pa.spice "
                   f"(sha256 {gdb.netlist_sha256()[:12]}) and "
                   "sim/ac-gain/ac_gain.spice (via gen_dut_benches.ac_gain_deck)")


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
